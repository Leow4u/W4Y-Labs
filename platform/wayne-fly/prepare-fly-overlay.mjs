#!/usr/bin/env node
// ===========================================================================
// Fly tenant overlay — generate the `.wayne.py` variants
// ===========================================================================
// Source of truth for the engine is the Work4You package tree
// (`work4you_cli`, `work4you_constants`, …). The Fly *base* image still lives
// under `/opt/wayne/` with import names `wayne_cli` / `wayne_constants` for
// historical reasons. Two mechanisms keep cloud aligned with desktop:
//
// 1) This script generates `.wayne.py` variants of selected files (pure
//    module renames) that Dockerfile.ui / publish-fly.ps1 COPY into place.
// 2) publish-fly.ps1 also stages the canonical `work4you_*.py` top-level
//    modules PLUS the thin `wayne_*.py` legacy aliases from the repo
//    (sys.modules swap). Work4You is truth; wayne_* re-exports — never the
//    reverse.
//
//     COPY work4you_cli/web_server.wayne.py /opt/wayne/wayne_cli/web_server.py
//
// Those variants are GENERATED, never hand-edited. They are pure module
// renames of their canonical source — verified: applying the table below to
// each source reproduces every committed variant exactly.
//
// Why this file is the enforcement point: without it, editing
// `work4you_cli/web_server.py` fixes the desktop and the tests while the
// cloud keeps running the stale 15k-line copy, with no signal that the two
// diverged. `publish-fly.ps1` runs this before `docker build`, so a forgotten
// regeneration cannot reach a tenant.
//
// It is Node, not PowerShell, for the same reason the engine runtime builder
// was ported (see wayne-agent/scripts/build-engine-runtime.mjs): a
// Windows-only build step silently breaks the macOS/Linux CI that also needs
// to verify this. The PowerShell predecessor additionally got saved as
// UTF-16LE with no BOM, which made it unparseable by the very shell it
// targeted — it never ran once.
//
// Usage:
//   node prepare-fly-overlay.mjs            # (re)generate the variants
//   node prepare-fly-overlay.mjs --check    # exit 1 if any is stale/missing
// ===========================================================================

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "..", "..");
const ENGINE_ROOT = path.join(REPO_ROOT, "wayne-agent");

/**
 * Module renames applied to every generated variant.
 *
 * Matched on word boundaries so `work4you_cli` does not also rewrite a
 * longer identifier that merely starts with it.
 */
const RENAMES = [
  ["work4you_cli", "wayne_cli"],
  ["work4you_constants", "wayne_constants"],
  ["work4you_state", "wayne_state"],
  ["work4you_logging", "wayne_logging"],
  ["work4you_bootstrap", "wayne_bootstrap"],
  ["work4you_time", "wayne_time"],
];

/**
 * `stateOnly` skips the `work4you_cli` rename.
 *
 * `work4you_state.py` becomes a TOP-LEVEL module in the image (`wayne_state`),
 * so its own name must change — but its comments cite `work4you_cli/...`
 * source paths as prose. Rewriting those would make the file claim to
 * document files that do not exist under either name.
 */
const PAIRS = [
  { src: "work4you_cli/platform_tenant.py" },
  { src: "work4you_cli/plan_model_gating.py" },
  { src: "work4you_cli/relay_free_model.py" },
  { src: "work4you_cli/web_server.py" },
  { src: "work4you_cli/restart_jobs.py" },
  { src: "work4you_cli/dashboard_auth/platform_sso.py" },
  { src: "work4you_cli/dashboard_auth/cookies.py" },
  { src: "work4you_cli/dashboard_auth/routes.py" },
  { src: "work4you_cli/dashboard_auth/middleware.py" },
  { src: "work4you_cli/dashboard_auth/login_page.py" },
  { src: "work4you_cli/dashboard_auth/ws_tickets.py" },
  { src: "work4you_state.py", dst: "wayne_state.wayne.py", stateOnly: true },
];

const BANNER =
  "# GENERATED by platform/wayne-fly/prepare-fly-overlay.mjs — DO NOT EDIT.\n" +
  "# Source of truth: %SRC%\n";

function variantPath(pair) {
  return pair.dst ?? pair.src.replace(/\.py$/, ".wayne.py");
}

function render(pair) {
  const srcPath = path.join(ENGINE_ROOT, pair.src);
  if (!fs.existsSync(srcPath)) {
    throw new Error(`missing canonical source: ${srcPath}`);
  }
  // Normalize to LF: the variant is consumed by a Linux container, and a
  // mixed-ending file would make every regeneration look like a full rewrite.
  let text = fs.readFileSync(srcPath, "utf8").replace(/\r\n/g, "\n");
  for (const [from, to] of RENAMES) {
    if (pair.stateOnly && from === "work4you_cli") continue;
    text = text.replace(new RegExp(`\\b${from}\\b`, "g"), to);
  }
  return BANNER.replace("%SRC%", pair.src) + text;
}

function main() {
  const check = process.argv.includes("--check");
  const stale = [];
  let written = 0;

  for (const pair of PAIRS) {
    const rel = variantPath(pair);
    const dstPath = path.join(ENGINE_ROOT, rel);
    const next = render(pair);
    const current = fs.existsSync(dstPath)
      ? fs.readFileSync(dstPath, "utf8").replace(/\r\n/g, "\n")
      : null;

    if (current === next) continue;

    if (check) {
      stale.push({ rel, reason: current === null ? "missing" : "stale" });
      continue;
    }
    fs.writeFileSync(dstPath, next, { encoding: "utf8" });
    console.log(`  regenerated ${rel}`);
    written += 1;
  }

  if (check) {
    if (stale.length === 0) {
      console.log(`[overlay] all ${PAIRS.length} Fly variants are in sync.`);
      return;
    }
    console.error(
      "[overlay] Fly overlay variants are out of date — the cloud would run " +
        "stale code:\n",
    );
    for (const { rel, reason } of stale) console.error(`    ${reason.padEnd(8)} ${rel}`);
    console.error(
      "\n  Regenerate and commit:\n" +
        "    node platform/wayne-fly/prepare-fly-overlay.mjs\n",
    );
    process.exit(1);
  }

  console.log(
    written === 0
      ? `[overlay] already in sync (${PAIRS.length} variants).`
      : `[overlay] regenerated ${written} of ${PAIRS.length} variants.`,
  );
}

try {
  main();
} catch (err) {
  console.error(`[overlay] ${err && err.message ? err.message : err}`);
  process.exit(1);
}
